def dieu_Chinh_Anh_Dau_Vao_lay_Canny_VIP(image):
  if len(image.shape) == 3:
      gray = cv2.cvtColor(image, cv2.COLOR_BGR2GRAY)
  else:
      gray = image.copy()
  clahe = cv2.createCLAHE(clipLimit=3.0, tileGridSize=(8,8))
  gray = clahe.apply(gray)
  gray = cv2.fastNlMeansDenoising(gray, None, 10, 7, 21)
  lap = cv2.Laplacian(gray, cv2.CV_64F)
  sharp = cv2.convertScaleAbs(gray - 0.5 * lap)
  blur = cv2.bilateralFilter(sharp, 9, 75, 75)
  binary = cv2.adaptiveThreshold( blur, 255, cv2.ADAPTIVE_THRESH_MEAN_C, cv2.THRESH_BINARY_INV, 35, 5)
  kernel = np.ones((3,3), np.uint8)
  binary = cv2.morphologyEx(binary, cv2.MORPH_CLOSE, kernel, iterations=2)
  return binary

