  da_co_dau_phay = False
  start = 0
  n = len(ky_tu_list)
  while start < n and ky_tu_list[start] == "":
    start += 1
  if start == n:
    ket_qua = ""
  else:
    sub = ky_tu_list[start:]

    for i, kt in enumerate(sub):
      if kt == "":
        continue
      if kt == "Co nhieu hon 1 dap an":
        return ""

      if kt == "-":
        if i != 0:
          return ""
