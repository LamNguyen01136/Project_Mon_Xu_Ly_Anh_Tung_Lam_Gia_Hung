def ghep_so(ky_tu):
    if len(ky_tu) == 0:
        return "null"
    dau_am = False
    so = ""
    co_phay = False
    for i, kt in enumerate(ky_tu):

        if kt == "null":
            continue
        if kt == "-":
            dau_am = True
        elif kt == ",":
            if co_phay:
                return ""
            co_phay = True
            so += "."
        else:
            so += kt
    if so == "":
        return ""
    if dau_am:
        so = "-" + so
    return so

"""Hàm tạo ma trận đáp án"""

def tao_Ma_Tran_Dap_An(image, ty_le_hang, ty_le_cot):
    cao, rong = image.shape[:2]
    so_hang = len(ty_le_hang) -1
    so_cot = len(ty_le_cot) - 1
    ma_Tran = np.zeros((so_hang, so_cot), dtype=np.int32)
    ma_Tran_ti_le_to = np.zeros((so_hang, so_cot), dtype=np.float32)
    for i in range(so_hang):
        y_start = int(ty_le_hang[i] * cao)
        y_end = int(ty_le_hang[i+1] * cao)
        for j in range(so_cot):
            x_start = int(ty_le_cot[j]   * rong)
            x_end   = int(ty_le_cot[j+1] * rong)
            o_anh = image[y_start:y_end, x_start:x_end]
            if o_anh.size == 0:
                continue
            h, w = o_anh.shape
            h_bd = int(h * 0.4)
            h_kt = int(h * 0.6)
            w_bd = int(w * 0.4)
            w_kt = int(w * 0.6)
            vung_trung_tam = o_anh[h_bd:h_kt, w_bd:w_kt]
            so_pixel_to = np.count_nonzero(vung_trung_tam)
            tong_pixel = vung_trung_tam.size
            ti_le_to = so_pixel_to / tong_pixel
            ma_Tran_ti_le_to[i, j] = ti_le_to
    return ma_Tran_ti_le_to

"""Tạo ma trận chấm mã đề"""

def tao_Ma_Tran_Ma_De(image, ty_le_hang, ty_le_cot):
    cao, rong = image.shape[:2]
    so_hang = len(ty_le_hang) -1
    so_cot = len(ty_le_cot) - 1
    ma_Tran = np.zeros((so_hang, so_cot), dtype=np.int32)
    ma_Tran_ti_le_to = np.zeros((so_hang, so_cot), dtype=np.float32)
    for i in range(so_hang):
        y_start = int(ty_le_hang[i]   * cao)
        y_end = int(ty_le_hang[i+1] * cao)
        for j in range(so_cot):
            x_start = int(ty_le_cot[j]   * rong)
            x_end   = int(ty_le_cot[j+1] * rong)
            o_anh = image[y_start:y_end, x_start:x_end]
            if o_anh.size == 0:
                continue
            nguong_To, image_phan_nguong= cv2.threshold(o_anh, 0, 255, cv2.THRESH_BINARY + cv2.THRESH_OTSU)
            h, w = image_phan_nguong.shape
            mask = np.zeros((h, w), dtype=np.uint8)
            cx, cy = w // 2, h // 2
            r = int(min(h, w) * 0.35)
            cv2.circle(mask, (cx, cy), r, 255, -1)
            vung_trung_tam = cv2.bitwise_and(image_phan_nguong, image_phan_nguong, mask=mask)
            so_pixel_to = np.count_nonzero(vung_trung_tam)
            tong_pixel = np.count_nonzero(mask)
            ti_le_to = so_pixel_to / tong_pixel
            ma_Tran_ti_le_to[i, j] = ti_le_to
    return ma_Tran_ti_le_to

