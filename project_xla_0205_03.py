"""Hàm tính góc"""

def tinh_goc(p1, p2, p3):
    v1 = p1 - p2
    v2 = p3 - p2
    cos_goc = np.dot(v1, v2) / (np.linalg.norm(v1) * np.linalg.norm(v2) + 1e-6)
    goc = np.degrees(np.arccos(cos_goc))
    return goc

"""Hàm tìm contour hình chữ nhật bao ngoài khung trả lời"""

def tim_contour_bao_ngoai(image, minArea, maxArea, socanh):
  image_Copy = image.copy()
  contour, hierarchy = cv2.findContours(image_Copy, cv2.RETR_LIST, cv2.CHAIN_APPROX_SIMPLE)
  contour_loc = []
  khung_can_tim = []
  for contour_phan in contour:
    dien_tich = cv2.contourArea(contour_phan)
    if (dien_tich > minArea) and (dien_tich < maxArea):
      peri = cv2.arcLength(contour_phan, True)
      approx = cv2.approxPolyDP(contour_phan, 0.02*peri, True)
      if (len(approx) == socanh):
        pts = approx.reshape(-1, 2)
        hop_le = True
        for i in range(4):
          p1 = pts[i]
          p2 = pts[(i+1) % 4]
          p3 = pts[(i+2) % 4]
          goc = tinh_goc(p1, p2, p3)
          if not (87 <= goc <= 93):
            hop_le = False
            break
        if not hop_le:
            continue
        x, y, w, h = cv2.boundingRect(contour_phan)
        if ((w > 455 and w < 550) and (h > 375 and h < 475)):
          continue
        contour_loc.append((approx, dien_tich, (x, y, w, h)))
  contour_loc.sort(key=lambda c: c[1], reverse=True)
  khung_kich_thuoc = []
  for approx, dien_tich, (x, y, w, h) in contour_loc:
        bi_loai = False
        for (cx, cy, cw, ch) in khung_kich_thuoc:
            xA = max(x, cx)
            yA = max(y, cy)
            xB = min(x + w, cx + cw)
            yB = min(y + h, cy + ch)
            interArea = max(0, xB - xA) * max(0, yB - yA)
            area_nho = min(w * h, cw * ch)
            if interArea > 0.9 * area_nho:
                bi_loai = True
                break
            if (x >= cx and y >= cy and x + w <= cx + cw and y + h <= cy + ch):
                nguong = 30
                canh_tiep_xuc = 0
                if abs(x - cx) <= nguong:
                    canh_tiep_xuc += 1
                if abs((x + w) - (cx + cw)) <= nguong:
                    canh_tiep_xuc += 1
                if abs(y - cy) <= nguong:
                    canh_tiep_xuc += 1
                if abs((y + h) - (cy + ch)) <= nguong:
                    canh_tiep_xuc += 1
                if canh_tiep_xuc >= 2:
                    bi_loai = True
                    break
        if not bi_loai:
            khung_can_tim.append((approx, dien_tich, w, h))
            khung_kich_thuoc.append((x, y, w, h))
  return khung_can_tim

