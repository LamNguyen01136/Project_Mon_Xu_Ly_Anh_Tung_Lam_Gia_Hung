def tinh_ket_qua_phan1_fc(fc_hs, fc_dung):
    ket_qua = []
    so_cau_dung = 0

    for i in range(1, 41):
        hs = fc_hs.get(str(i), [])
        dung = fc_dung.get(str(i), [])

        if hs == dung and len(hs) > 0:
            ket_qua.append("D")
            so_cau_dung += 1
        else:
            ket_qua.append("S")

    return so_cau_dung, ket_qua



def tinh_ket_qua_phan2_tf(tf_hs, tf_dung):
    ket_qua = []
    so_cau_dung = 0

    for i in range(1, 33):
        hs = tf_hs.get(str(i), [])
        dung = tf_dung.get(str(i), [])

        cau_kq = []

        for j in range(4):
            if (j in hs) == (j in dung):
                cau_kq.append("D")
                if j in dung:
                    so_cau_dung += 1
            else:
                cau_kq.append("S")

        ket_qua.append(cau_kq)

    return so_cau_dung, ket_qua




def tinh_ket_qua_phan3_dg(dg_hs, dg_dung):
    ket_qua = []
    so_cau_dung = 0

    for i in range(1, 7):
        hs = dg_hs.get(str(i), "")
        dung = dg_dung.get(str(i), "")

        try:
            hs_val = float(hs.replace(",", "."))
            dung_val = float(dung.replace(",", "."))

            if hs_val == dung_val:
                ket_qua.append("D")
                so_cau_dung += 1
            else:
                ket_qua.append("S")
        except:
            ket_qua.append("S")

    return so_cau_dung, ket_qua




