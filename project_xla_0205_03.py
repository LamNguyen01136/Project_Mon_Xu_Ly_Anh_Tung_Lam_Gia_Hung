def tim_4_goc(arrayA):
  arrayA = arrayA.reshape(4, 2).astype("float32")
  mang_da_sap_xep = np.zeros((4, 2), dtype = "float32")
  tong = arrayA.sum(axis=1)
  hieu = np.diff(arrayA, axis=1)
  mang_da_sap_xep[0] = arrayA[np.argmin(tong)]
  mang_da_sap_xep[1] = arrayA[np.argmin(hieu)]
  mang_da_sap_xep[2] = arrayA[np.argmax(tong)]
  mang_da_sap_xep[3] = arrayA[np.argmax(hieu)]
  return mang_da_sap_xep

"""Hàm sắp xếp contour"""

def sap_xep_contour(contours):
    rects = [cv2.boundingRect(c[0]) for c in contours]
    heights = [h for (x, y, w, h) in rects]
    median_h = np.median(heights) if heights else 50
    gap_threshold = 0.5 * median_h
    contours_info = [(c, r[0], r[1]) for c, r in zip(contours, rects)]
    contours_info.sort(key=lambda t: t[2])
    rows = []
    if contours_info:
        current_row = [contours_info[0]]
        for i in range(1, len(contours_info)):
            last_y = current_row[-1][2]
            cur_y = contours_info[i][2]
            if cur_y - last_y < gap_threshold:
                current_row.append(contours_info[i])
            else:
                rows.append(current_row)
                current_row = [contours_info[i]]
        rows.append(current_row)
    rows.reverse()
    sorted_contours = []
    for row in rows:
        row.sort(key=lambda t: t[1])
        for cnc, _, _ in row:
            sorted_contours.append(cnc)
    return sorted_contours

